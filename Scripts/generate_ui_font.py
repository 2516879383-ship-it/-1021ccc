"""Rebuild the dashboard's small 20px Chinese glyph subset (Pillow).

Only glyphs appearing in UTF-8 string literals in qr_ui.c are included.
The font path is explicit so no external SPI-flash font is required at runtime.
"""
import argparse
import ast
from pathlib import Path
import re
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument("--font", default="C:/Windows/Fonts/simhei.ttf")
parser.add_argument("--keep-existing", action="store_true",
                    help="Reuse existing bitmaps for retained characters; render only new ones")
args = parser.parse_args()
source = (root / "User/app/qr_ui.c").read_text(encoding="gbk")
literals = re.findall(r'"(?:[^"\\]|\\.)*"', source)
labels = [ast.literal_eval(s).encode("latin1").decode("utf-8") for s in literals]
chars = sorted({c for s in labels for c in s if ord(c) >= 128}, key=ord)
output = root / "User/fonts/ui_glyphs.h"
existing = {}
if args.keep_existing:
    existing = {int(code, 16): line for line, code in re.findall(
        r"(    \{0x([0-9A-F]+), \{[^\n]+)", output.read_text(encoding="ascii"))}
font = ImageFont.truetype(args.font, 20)
lines = ["/* Generated by Scripts/generate_ui_font.py; 20x20, MSB first. */",
         "#ifndef UI_GLYPHS_H", "#define UI_GLYPHS_H", "#include <stdint.h>",
         f"#define UI_GLYPH_COUNT {len(chars)}u",
         "static const struct { uint16_t code; uint8_t bits[60]; } ui_glyphs[] = {"]
for c in chars:
    if ord(c) in existing:
        lines.append(existing[ord(c)])
        continue
    image = Image.new("1", (20, 20))
    ImageDraw.Draw(image).text((0, 0), c, font=font, fill=1, anchor="lt")
    data = []
    for y in range(20):
        for b in range(3):
            data.append(sum((0x80 >> j) for j in range(8)
                            if b * 8 + j < 20 and image.getpixel((b * 8 + j, y))))
    lines.append(f"    {{0x{ord(c):04X}, {{" + ",".join(f"0x{v:02X}" for v in data) + "}},")
lines += ["};", "#endif", ""]
output.write_text("\n".join(lines), encoding="ascii")
print(f"Generated {len(chars)} glyphs ({len(chars) * 62} bytes)")
